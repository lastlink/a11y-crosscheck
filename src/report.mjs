export function createReporter(plan, browser) {
  const { base, pages, runs, out, site, stamp, engines } = plan;
  /** axe reports per run (page x theme x viewport, plus states); the other engines per page. */
  const axeKeys = runs.map((r) => r.key);

  function page(title, bodyHtml) {
    return `<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>${esc(title)}</title><style>${CSS}</style></head><body><main>
${bodyHtml}
<footer>Generated by <code>a11y-crosscheck</code> against <code>${esc(base)}</code> using <code>${esc(path.basename(browser))}</code>.</footer>
</main></body></html>
`;
  }

  function write(dir, name, title, data, bodyHtml) {
    mkdirSync(dir, { recursive: true });
    const file = path.join(dir, name);
    writeFileSync(
      `${file}.json`,
      JSON.stringify(
        { generated: new Date().toISOString(), base, browser, engines, pages, runs, ...data },
        null,
        2
      )
    );
    writeFileSync(`${file}.html`, page(title, bodyHtml));
    return { json: `${file}.json`, html: `${file}.html` };
  }

  function axeHtml(data) {
    const rows = axeKeys
      .map((p) => {
        const r = data[p];
        if (!r) return "";
        if (r.unreachable) {
          return `<tr><th scope="row"><code>${esc(p)}</code></th>
      <td class="bad" colspan="3">skipped - ${esc(r.unreachable)}</td></tr>`;
        }
        const nodes = r.violations.reduce((s, v) => s + v.nodes.length, 0);
        return `<tr><th scope="row"><code>${esc(p)}</code>${r.notReady ? ' <span class="tag warn">never matched ready</span>' : ""}</th>
      <td class="${r.violations.length ? "bad" : "ok"}">${r.violations.length}</td>
      <td class="${r.violations.length ? "bad" : "ok"}">${nodes}</td>
      <td class="${r.incompleteNew ? "warn" : "ok"}">${r.incompleteAcknowledged + r.incompleteNew} node(s)${
        r.incompleteNew
          ? ` &middot; <strong>${r.incompleteNew} new</strong>`
          : " &middot; all acknowledged"
      }</td></tr>`;
      })
      .join("\n");
    const secs = axeKeys
      .map((p) => {
        const r = data[p];
        if (!r) return "";
        const bits = [];
        if (r.violations.length) {
          bits.push(
            "<h4>Violations</h4><ul>" +
              r.violations
                .map(
                  (v) =>
                    `<li><strong>${esc(v.id)}</strong> <span class="tag">${esc(v.impact)}</span> <span class="tag">${esc(v.tags.join(", "))}</span><br>${esc(v.help)}<ul>` +
                    v.nodes
                      .map((n) => `<li><code>${esc(n.target)}</code><pre>${esc(n.html)}</pre></li>`)
                      .join("") +
                    "</ul></li>"
                )
                .join("") +
              "</ul>"
          );
        }
        if (r.incomplete.length) {
          bits.push(
            `<h4>Needs review <span class="tag">${r.incompleteNew} new</span> <span class="tag">${
              r.incompleteAcknowledged
            } acknowledged</span></h4><ul>` +
              r.incomplete
                .map(
                  (v) =>
                    `<li><code>${esc(v.id)}</code> <span class="tag">${v.count} node(s)</span>${
                      v.newCount ? ` <span class="tag bad">${v.newCount} new</span>` : ""
                    }<br>${esc(v.help)}<ul>` +
                    (v.nodes || [])
                      .map(
                        (n) =>
                          `<li><code>${esc(n.target)}</code> ${
                            n.acknowledged
                              ? `<span class="tag">acknowledged${n.reason ? ": " + esc(n.reason) : ""}</span>`
                              : `<span class="tag bad">NEW${n.reason ? ": " + esc(n.reason) : ""}</span><pre>${esc(n.html)}</pre>`
                          }</li>`
                      )
                      .join("") +
                    (v.unlisted
                      ? `<li><span class="tag bad">${v.unlisted} further node(s) not listed</span></li>`
                      : "") +
                    "</ul></li>"
                )
                .join("") +
              "</ul>"
          );
        }
        return bits.length ? `<section><h3><code>${esc(p)}</code></h3>${bits.join("")}</section>` : "";
      })
      .join("\n");
    const total = axeKeys.reduce((s, p) => s + (data[p]?.violations.length || 0), 0);
    const scope =
      `${pages.length} page(s) x ${plan.themes.values.length} theme(s) x ` +
      `${plan.viewportNames.length} viewport(s), plus ${runs.filter((r) => r.steps).length} state(s) = ${axeKeys.length} runs`;
    return `<h1>axe-core</h1>
<p class="meta">${esc(new Date().toISOString())} &middot; tags ${esc(plan.axe.tags.join(", "))} &middot; ${esc(scope)}</p>
<div class="verdict ${total ? "dirty" : "clean"}">${total ? `${total} violation rule(s) across ${axeKeys.length} runs.` : `No violations across ${axeKeys.length} runs.`}</div>
<table><caption>Per run</caption><thead><tr><th>Page</th><th>Violation rules</th><th>Nodes</th><th>Needs review</th></tr></thead><tbody>${rows}</tbody></table>
${secs}`;
  }

  function pa11yHtml(data) {
    const rows = pages
      .map((p) => {
        const r = data[p];
        if (!r) return "";
        if (r.error)
          return `<tr><th scope="row"><code>${esc(p)}</code></th><td class="bad" colspan="2">${esc(r.error)}</td></tr>`;
        const errs = r.issues.filter((i) => i.type === "error").length;
        return `<tr><th scope="row"><code>${esc(p)}</code></th>
      <td class="${r.issues.length ? "bad" : "ok"}">${r.issues.length}</td>
      <td class="${errs ? "bad" : "ok"}">${errs}</td></tr>`;
      })
      .join("\n");
    const secs = pages
      .map((p) => {
        const r = data[p];
        if (!r || r.error || !r.issues.length) return "";
        return (
          `<section><h3><code>${esc(p)}</code></h3><ul>` +
          r.issues
            .slice(0, 60)
            .map(
              (i) =>
                `<li><code>${esc(i.code)}</code> <span class="tag">${esc(i.type)}</span><br>${esc(i.message)}<pre>${esc(i.selector)}</pre></li>`
            )
            .join("") +
          "</ul></section>"
        );
      })
      .join("\n");
    const total = pages.reduce((s, p) => s + (data[p]?.issues?.length || 0), 0);
    const anyErr = pages.some((p) => data[p]?.error);
    return `<h1>pa11y</h1>
<p class="meta">${esc(new Date().toISOString())} &middot; HTML_CodeSniffer, standard ${esc(plan.pa11y.standard)}</p>
<div class="verdict ${total || anyErr ? "dirty" : "clean"}">${anyErr ? "Some pages failed to run - see the table." : total ? `${total} issue(s) across ${pages.length} pages.` : `No issues across ${pages.length} pages.`}</div>
<table><caption>Per page</caption><thead><tr><th>Page</th><th>Issues</th><th>Errors</th></tr></thead><tbody>${rows}</tbody></table>
${secs}`;
  }

  function lighthouseHtml(data) {
    const rows = pages
      .map((p) => {
        const r = data[p];
        if (!r) return "";
        if (r.error)
          return `<tr><th scope="row"><code>${esc(p)}</code></th><td class="bad" colspan="2">${esc(r.error)}</td></tr>`;
        return `<tr><th scope="row"><code>${esc(p)}</code></th>
      <td class="${r.score === 100 ? "ok" : "bad"}">${r.score}</td>
      <td class="${r.failures.length ? "bad" : "ok"}">${r.failures.length}</td></tr>`;
      })
      .join("\n");
    const secs = pages
      .map((p) => {
        const r = data[p];
        if (!r || r.error || !r.failures.length) return "";
        return (
          `<section><h3><code>${esc(p)}</code> <span class="tag">score ${r.score}</span></h3><ul>` +
          r.failures
            .map(
              (f) =>
                `<li><code>${esc(f.id)}</code> <span class="tag">weight ${f.weight}</span> <span class="tag">${f.nodes} node(s)</span><br>${esc(f.title)}` +
                (f.targets?.length
                  ? "<ul>" + f.targets.map((t) => `<li><pre>${esc(t)}</pre></li>`).join("") + "</ul>"
                  : "") +
                "</li>"
            )
            .join("") +
          "</ul></section>"
        );
      })
      .join("\n");
    const scores = pages.map((p) => data[p]?.score).filter((s) => typeof s === "number");
    const min = scores.length ? Math.min(...scores) : null;
    return `<h1>Lighthouse</h1>
<p class="meta">${esc(new Date().toISOString())} &middot; accessibility category only</p>
<div class="verdict ${min === 100 ? "clean" : "dirty"}">${min === null ? "No scores captured." : min === 100 ? `All ${scores.length} pages score 100.` : `Lowest score ${min} of ${scores.length} pages.`}</div>
<table><caption>Per page</caption><thead><tr><th>Page</th><th>Score</th><th>Failing audits</th></tr></thead><tbody>${rows}</tbody></table>
${secs}`;
  }

  function summaryHtml(results) {
    // Every row axe produced, plus any page only the other two covered.
    const keys = [...new Set([...axeKeys, ...pages])];
    const rows = keys
      .map((p) => {
        const a = results.axe?.[p],
          q = results.pa11y?.[p],
          l = results.lighthouse?.[p];
        const aN = a ? a.violations.reduce((s, v) => s + v.nodes.length, 0) : null;
        return `<tr><th scope="row"><code>${esc(p)}</code></th>
      ${a ? (a.unreachable ? '<td class="bad">skipped</td>' : `<td class="${a.violations.length ? "bad" : "ok"}">${a.violations.length} rule(s) / ${aN} node(s)</td>`) : '<td class="na">not run</td>'}
      ${
        a && !a.unreachable
          ? `<td class="${a.incompleteNew ? "warn" : "ok"}">${a.incompleteAcknowledged + a.incompleteNew}${
              a.incompleteNew ? ` (${a.incompleteNew} new)` : " (all acknowledged)"
            }</td>`
          : '<td class="na">-</td>'
      }
      ${q ? (q.error ? '<td class="bad">error</td>' : `<td class="${q.issues.length ? "bad" : "ok"}">${q.issues.length}</td>`) : '<td class="na">not run</td>'}
      ${l ? (l.error ? '<td class="bad">error</td>' : `<td class="${l.score === 100 ? "ok" : "bad"}">${l.score}</td>`) : '<td class="na">not run</td>'}
    </tr>`;
      })
      .join("\n");

    const axeRules = new Set(),
      lhRules = new Set(),
      paCodes = new Set();
    axeKeys.forEach((p) => results.axe?.[p]?.violations.forEach((v) => axeRules.add(v.id)));
    pages.forEach((p) => {
      results.lighthouse?.[p]?.failures?.forEach((f) => lhRules.add(f.id));
      results.pa11y?.[p]?.issues?.forEach((i) => paCodes.add(i.code));
    });
    const list = (s) =>
      s.size
        ? [...s]
            .sort()
            .map((x) => `<code>${esc(x)}</code>`)
            .join(", ")
        : '<span class="ok">none</span>';

    return `<h1>Accessibility summary</h1>
<p class="meta">${esc(new Date().toISOString())} &middot; target <code>${esc(base)}</code> &middot; engines: ${esc(engines.join(", "))}<br>browser <code>${esc(browser)}</code></p>
<table><caption>Per page, all engines</caption>
<thead><tr><th>Page</th><th>axe violations</th><th>axe needs-review</th><th>pa11y issues</th><th>Lighthouse score</th></tr></thead>
<tbody>${rows}</tbody></table>
<h2>Rules fired, by engine</h2>
<table><thead><tr><th>Engine</th><th>Rules / codes</th></tr></thead><tbody>
<tr><th scope="row">axe-core</th><td>${list(axeRules)}</td></tr>
<tr><th scope="row">Lighthouse</th><td>${list(lhRules)}</td></tr>
<tr><th scope="row">pa11y</th><td>${list(paCodes)}</td></tr>
</tbody></table>
<p class="meta">axe-core and Lighthouse share the axe engine, so Lighthouse findings are normally a
subset of axe's - Lighthouse runs a curated rule list and weights it into a score. pa11y uses
HTML_CodeSniffer, a separate implementation, so it can disagree with both in either direction.</p>`;
  }

  const html = { axe: axeHtml, pa11y: pa11yHtml, lighthouse: lighthouseHtml };
  const name = `${site}-${stamp}`;

  return {
    engine(engine, results) {
      return write(
        path.join(out, engine),
        name,
        `${engine} accessibility report ${stamp}`,
        { engine, results },
        html[engine](results)
      );
    },
    summary(results) {
      return write(
        out,
        `summary-${name}`,
        `Accessibility summary ${stamp}`,
        { results },
        summaryHtml(results)
      );
    }
  };
}
